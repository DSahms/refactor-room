import 'package:flutter_test/flutter_test.dart';
import 'package:refactor_room/models/analysis.dart';

void main() {
  test('parses inline Field: value transplant blocks', () {
    const block = '''
Viability tier: Strong
Target user: Remote employees who may feel disconnected from their colleagues and supervisors.
Adaptation: This transplant applies anonymous sharing and AI-driven content analysis to support remote employees in providing feedback.
MVP: A digital platform for anonymous sharing, AI-driven content analysis, and human oversight for crisis response.
First dollar: Generated by offering premium feedback and support services to remote employees.
Risk flags: Risk of misuse or exploitation; requires careful moderation protocols and community guidelines.
Current workaround: Use of email or project management tools, which often lack anonymity and adequate support resources.
Failure mode: Lack of engagement or participation due to concerns about anonymity or platform effectiveness.
Unfair advantage: The ability to provide a safe, anonymous space for sharing, which can increase employee engagement and retention.
''';

    final raw = '''
§ 02 — ALL TRANSPLANTS RANKED

03 — Remote Employee Feedback System
$block
''';

    final transplants = Analysis.parse(
      idea: 'test',
      skeletonRaw: '',
      transplantsRaw: raw,
    ).rankedTransplants;

    final t = transplants.firstWhere((x) => x.rank == 3);
    expect(t.title, 'Remote Employee Feedback System');
    expect(t.viabilityTier, ViabilityTier.strong);
    expect(t.targetUser, contains('Remote employees'));
    expect(t.adaptation, contains('anonymous sharing'));
    expect(t.mvp, contains('digital platform'));
    expect(t.firstDollar, contains('premium feedback'));
    expect(t.riskFlags.length, greaterThanOrEqualTo(2));
    expect(t.currentWorkaround, contains('email'));
    expect(t.failureMode, contains('engagement'));
    expect(t.unfairAdvantage, contains('anonymous space'));
    expect(t.hasStructuredFields, isTrue);
  });
}
